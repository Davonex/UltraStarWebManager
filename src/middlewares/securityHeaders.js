// @ts-check
/**
 * En-têtes de sécurité ajoutés à toutes les réponses.
 * @module middlewares/securityHeaders
 */

/**
 * Politique de contenu : seuls les fichiers de ce serveur peuvent être chargés et exécutés
 * (pas de script en ligne, pas de domaine extérieur). `data:` est nécessaire aux petites
 * icônes SVG intégrées au CSS de Bootstrap.
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "media-src 'self'",
  "connect-src 'self'",
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const HEADERS = Object.freeze({
  'Content-Security-Policy': CONTENT_SECURITY_POLICY,
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'no-referrer',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=()',
});

/**
 * @param {import('express').Request} _req
 * @param {import('express').Response} res
 * @param {import('express').NextFunction} next
 */
export function securityHeaders(_req, res, next) {
  res.set(HEADERS);
  next();
}
